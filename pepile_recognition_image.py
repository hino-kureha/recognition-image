import cv2
import numpy as np
import matplotlib.pyplot as plt
from ultralytics import YOLO


class BodyShapeAnalyzerRobust:
    # Índices COCO
    NOSE, L_EYE, R_EYE, L_EAR, R_EAR = 0, 1, 2, 3, 4
    L_SHOULDER, R_SHOULDER = 5, 6
    L_ELBOW, R_ELBOW = 7, 8
    L_WRIST, R_WRIST = 9, 10
    L_HIP, R_HIP = 11, 12
    L_KNEE, R_KNEE = 13, 14
    L_ANKLE, R_ANKLE = 15, 16

    def __init__(self, img_path, pose_model="yolov8n-pose.pt", seg_model="yolov8n-seg.pt",
                 ref_pixel_width=None, ref_cm_width=None):
        self.img_path = img_path
        self.img_bgr = cv2.imread(img_path)
        if self.img_bgr is None:
            raise FileNotFoundError(f"No se pudo leer {img_path}")
        self.img_rgb = cv2.cvtColor(self.img_bgr, cv2.COLOR_BGR2RGB)

        print("Cargando modelos...")
        self.pose_model = YOLO(pose_model)
        self.seg_model = YOLO(seg_model)
        print("Modelos listos.\n")

        self.ref_pixel_width = ref_pixel_width
        self.ref_cm_width = ref_cm_width
        self.calibration_mode = "objeto_referencia" if (ref_pixel_width and ref_cm_width) else "sin_calibrar"

    # ---------- DETECCIÓN BASE ----------
    def detect_pose(self, conf=0.35):
        results = self.pose_model(self.img_bgr, conf=conf, verbose=False)[0]
        self.people = []
        if results.keypoints is None or len(results.boxes) == 0:
            return []
        for box, kpts in zip(results.boxes, results.keypoints):
            xyxy = box.xyxy[0].cpu().numpy().astype(int)
            kp = kpts.xy[0].cpu().numpy()
            kp_conf = kpts.conf[0].cpu().numpy() if kpts.conf is not None else np.ones(17)
            self.people.append({"bbox": xyxy, "keypoints": kp, "kp_conf": kp_conf})
        print(f"Personas detectadas: {len(self.people)}")
        return self.people

    def detect_masks(self, conf=0.35):
        results = self.seg_model(self.img_bgr, conf=conf, classes=[0], verbose=False)[0]
        self.masks = []
        if results.masks is None:
            return []
        h, w = self.img_bgr.shape[:2]
        for mask_data, box in zip(results.masks.data, results.boxes):
            mask = cv2.resize(mask_data.cpu().numpy(), (w, h))
            self.masks.append({"mask": (mask > 0.5).astype(np.uint8),
                                "bbox": box.xyxy[0].cpu().numpy().astype(int)})
        return self.masks

    def match_pose_to_mask(self, person):
        px1, py1, px2, py2 = person["bbox"]
        center = np.array([(px1 + px2) / 2, (py1 + py2) / 2])
        best_mask, best_dist = None, float("inf")
        for m in self.masks:
            mx1, my1, mx2, my2 = m["bbox"]
            mcenter = np.array([(mx1 + mx2) / 2, (my1 + my2) / 2])
            dist = np.linalg.norm(center - mcenter)
            if dist < best_dist:
                best_dist, best_mask = dist, m
        return best_mask

    # ---------- 1. DETECTAR ORIENTACIÓN / ÁNGULO DE LA PERSONA ----------
    def estimate_orientation(self, person):
        """
        Determina si la persona está de frente, perfil, 3/4 o espalda,
        y devuelve un score de confiabilidad (0-1) para las medidas de ancho.
        """
        kp = person["keypoints"]
        conf = person["kp_conf"]

        def valid(idx, min_conf=0.3):
            return conf[idx] > min_conf and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        info = {"vista": "indeterminada", "confiabilidad": 0.0, "razones": []}

        # --- Señal 1: ¿se ven ambos hombros y ambas caderas? (clave para perfil vs frente) ---
        both_shoulders = valid(self.L_SHOULDER) and valid(self.R_SHOULDER)
        both_hips = valid(self.L_HIP) and valid(self.R_HIP)
        both_ears = valid(self.L_EAR) and valid(self.R_EAR)
        both_eyes = valid(self.L_EYE) and valid(self.R_EYE)

        if not both_shoulders:
            info["vista"] = "perfil o muy angulada"
            info["razones"].append("Solo se detecta un hombro con confianza → probable perfil")
            info["confiabilidad"] = 0.15
            return info

        # --- Señal 2: ancho hombro vs ancho de cara (en perfil, el ancho de "cara" colapsa) ---
        shoulder_width = np.linalg.norm(kp[self.L_SHOULDER] - kp[self.R_SHOULDER])
        if both_ears:
            ear_width = np.linalg.norm(kp[self.L_EAR] - kp[self.R_EAR])
        elif both_eyes:
            ear_width = np.linalg.norm(kp[self.L_EYE] - kp[self.R_EYE]) * 1.8
        else:
            ear_width = None

        # --- Señal 3: nariz centrada entre hombros (indica frontalidad) ---
        nose_centering = None
        if valid(self.NOSE):
            mid_shoulder_x = (kp[self.L_SHOULDER][0] + kp[self.R_SHOULDER][0]) / 2
            nose_centering = abs(kp[self.NOSE][0] - mid_shoulder_x) / shoulder_width if shoulder_width else None

        # --- Señal 4: inclinación del eje hombro-cadera respecto a la vertical (persona agachada/torcida) ---
        tilt_deg = None
        if both_shoulders and both_hips:
            mid_shoulder = (kp[self.L_SHOULDER] + kp[self.R_SHOULDER]) / 2
            mid_hip = (kp[self.L_HIP] + kp[self.R_HIP]) / 2
            dx, dy = mid_hip[0] - mid_shoulder[0], mid_hip[1] - mid_shoulder[1]
            tilt_deg = abs(np.degrees(np.arctan2(dx, dy)))

        # --- Decisión combinada ---
        score = 1.0
        if nose_centering is not None:
            if nose_centering > 0.35:
                info["vista"] = "3/4 (girada)"
                info["razones"].append(f"Nariz descentrada respecto a hombros ({nose_centering:.2f}) → vista 3/4")
                score *= 0.6
            else:
                info["razones"].append(f"Nariz centrada respecto a hombros ({nose_centering:.2f}) → vista frontal")

        if not info["razones"]:
            info["vista"] = "frontal (asumida)"

        if info["vista"] == "indeterminada":
            info["vista"] = "frontal (asumida)"

        if tilt_deg is not None:
            if tilt_deg > 15:
                info["razones"].append(f"Torso inclinado {tilt_deg:.1f}° respecto a vertical → postura no erguida")
                score *= max(0.4, 1 - (tilt_deg - 15) / 60)

        if not both_hips:
            info["razones"].append("Caderas no visibles con confianza → no se puede medir cintura/cadera")
            score *= 0.3

        # Penalizar por confianza baja general de los keypoints clave
        key_confs = [conf[i] for i in [self.L_SHOULDER, self.R_SHOULDER, self.L_HIP, self.R_HIP] if conf[i] > 0]
        if key_confs:
            avg_conf = np.mean(key_confs)
            score *= avg_conf

        info["confiabilidad"] = round(float(np.clip(score, 0, 1)), 2)
        info["_tilt_deg"] = tilt_deg
        return info

    # ---------- 2. ANCHO CORREGIDO POR ROTACIÓN EN EL PLANO ----------
    def get_width_at_y_corrected(self, mask, y, x_range, tilt_deg=None):
        """
        Si la persona está inclinada (tilt en el plano de la imagen, no de perfil real),
        el ancho horizontal puro subestima el ancho real del cuerpo. Se corrige dividiendo
        por el coseno de la inclinación. Esto NO corrige el caso de perfil real (rotación
        en profundidad), que ya se filtra aparte con la confiabilidad.
        """
        h, w = mask.shape
        y = int(np.clip(y, 0, h - 1))
        row = mask[y, :].copy()
        x0, x1 = x_range
        row[:max(0, x0)] = 0
        row[min(w, x1):] = 0
        xs = np.where(row > 0)[0]
        if len(xs) == 0:
            return None
        raw_width = int(xs.max() - xs.min())
        if tilt_deg and tilt_deg > 3:
            correction = np.cos(np.radians(min(tilt_deg, 45)))
            return round(raw_width * correction, 1) if correction > 0.3 else raw_width
        return raw_width

    # ---------- 3. MEDIR CON VALIDACIÓN DE CONFIABILIDAD ----------
    def measure_body_shape(self, person, mask_entry, orientation):
        kp = person["keypoints"]
        conf = person["kp_conf"]
        mask = mask_entry["mask"]
        mx1, my1, mx2, my2 = mask_entry["bbox"]
        tilt = orientation.get("_tilt_deg")

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        result = {}

        if valid(self.L_SHOULDER) and valid(self.R_SHOULDER):
            y_shoulder = int((kp[self.L_SHOULDER][1] + kp[self.R_SHOULDER][1]) / 2)
            result["ancho_hombros_px"] = self.get_width_at_y_corrected(mask, y_shoulder, (mx1, mx2), tilt)
            result["_y_shoulder"] = y_shoulder

        if valid(self.L_HIP) and valid(self.R_HIP):
            y_hip = int((kp[self.L_HIP][1] + kp[self.R_HIP][1]) / 2)
            result["ancho_caderas_px"] = self.get_width_at_y_corrected(mask, y_hip, (mx1, mx2), tilt)
            result["_y_hip"] = y_hip

        if "_y_shoulder" in result and "_y_hip" in result:
            y_waist = int(result["_y_shoulder"] + (result["_y_hip"] - result["_y_shoulder"]) * 0.58)
            result["ancho_cintura_px"] = self.get_width_at_y_corrected(mask, y_waist, (mx1, mx2), tilt)
            result["_y_waist"] = y_waist

        return result

    def get_px_to_cm_factor(self, person):
        if self.calibration_mode == "objeto_referencia":
            return self.ref_cm_width / self.ref_pixel_width
        kp, conf = person["keypoints"], person["kp_conf"]
        AVG_FACE_WIDTH_CM = 14.0

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        if valid(self.L_EAR) and valid(self.R_EAR):
            face_px = np.linalg.norm(kp[self.L_EAR] - kp[self.R_EAR])
        elif valid(self.L_EYE) and valid(self.R_EYE):
            face_px = np.linalg.norm(kp[self.L_EYE] - kp[self.R_EYE]) * 2.2
        else:
            return None
        return AVG_FACE_WIDTH_CM / face_px if face_px > 0 else None

    # ---------- 4. CLASIFICACIÓN (solo si confiabilidad suficiente) ----------
    def classify_body_shape(self, m, confiabilidad):
        if confiabilidad < 0.4:
            return {"tipo": "No confiable", "razon": "Ángulo/pose no permite una medición fiable de la silueta."}

        shoulder, waist, hip = m.get("ancho_hombros_px"), m.get("ancho_cintura_px"), m.get("ancho_caderas_px")
        if not (shoulder and waist and hip):
            return {"tipo": "Indeterminado", "razon": "Faltan medidas clave."}

        shoulder_hip_diff_pct = abs(shoulder - hip) / max(shoulder, hip) * 100
        waist_hip_ratio = waist / hip
        waist_shoulder_ratio = waist / shoulder
        detalles = [f"Hombro:{shoulder}px Cintura:{waist}px Cadera:{hip}px",
                    f"cintura/cadera={waist_hip_ratio:.2f}, cintura/hombro={waist_shoulder_ratio:.2f}"]

        if waist_hip_ratio > 0.90 and waist_shoulder_ratio > 0.90:
            tipo = "Manzana / Ovalado"
        elif shoulder_hip_diff_pct < 8 and waist_hip_ratio < 0.78:
            tipo = "Reloj de arena"
        elif hip > shoulder and (hip - shoulder) / shoulder * 100 > 8:
            tipo = "Pera / Triángulo"
        elif shoulder > hip and (shoulder - hip) / hip * 100 > 8:
            tipo = "Triángulo invertido"
        else:
            tipo = "Rectángulo"

        return {"tipo": tipo, "detalles": detalles,
                "waist_hip_ratio": round(waist_hip_ratio, 2)}

    # ---------- 5. PIPELINE COMPLETO ----------
    def analyze(self):
        self.detect_pose()
        self.detect_masks()
        self.results = []

        for i, person in enumerate(self.people):
            orientation = self.estimate_orientation(person)
            mask_entry = self.match_pose_to_mask(person)


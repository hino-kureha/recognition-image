import cv2
import numpy as np
import matplotlib.pyplot as plt
from ultralytics import YOLO
from sklearn.cluster import KMeans


class PersonClothingAnalyzer:
    def __init__(self, img_path, pose_model="yolov8n-pose.pt"):
        self.img_path = img_path
        self.img_bgr = cv2.imread(img_path)
        self.img_rgb = cv2.cvtColor(self.img_bgr, cv2.COLOR_BGR2RGB)
        if self.img_bgr is None:
            raise FileNotFoundError(f"No se pudo leer {img_path}")

        print("Cargando modelo de pose (descarga ~6MB la primera vez)...")
        self.pose_model = YOLO(pose_model)

        # Nombres de colores de referencia para clasificar el color dominante
        self.color_names = {
            "negro": (0, 0, 0), "blanco": (255, 255, 255), "gris": (128, 128, 128),
            "rojo": (200, 30, 30), "azul": (30, 60, 180), "azul_marino": (20, 30, 80),
            "verde": (40, 130, 60), "amarillo": (220, 200, 40), "naranja": (220, 120, 30),
            "rosa": (230, 130, 170), "morado": (120, 50, 150), "marrón": (110, 70, 40),
            "beige": (210, 190, 150), "celeste": (130, 190, 230)
        }

    # ---------- 1. DETECTAR PERSONAS + KEYPOINTS DE POSE ----------
    def detect_people(self, conf=0.4):
        results = self.pose_model(self.img_bgr, conf=conf, verbose=False)[0]
        self.people = []

        if results.keypoints is None or len(results.boxes) == 0:
            print("No se detectaron personas.")
            return []

        for i, (box, kpts) in enumerate(zip(results.boxes, results.keypoints)):
            xyxy = box.xyxy[0].cpu().numpy().astype(int)
            kp = kpts.xy[0].cpu().numpy()  # 17 keypoints COCO
            kp_conf = kpts.conf[0].cpu().numpy() if kpts.conf is not None else np.ones(17)
            self.people.append({"bbox": xyxy, "keypoints": kp, "kp_conf": kp_conf})

        print(f"Personas detectadas: {len(self.people)}")
        return self.people

    # ---------- 2. REGIONES DE ROPA A PARTIR DE KEYPOINTS COCO ----------
    # COCO keypoints: 0 nariz,5 hombro_izq,6 hombro_der,11 cadera_izq,12 cadera_der,
    #                 13 rodilla_izq,14 rodilla_der,15 tobillo_izq,16 tobillo_der
    def get_clothing_regions(self, person):
        kp = person["keypoints"]
        conf = person["kp_conf"]

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        regions = {}

        # Torso (camiseta/blusa/campera): entre hombros y caderas
        if valid(5) and valid(6) and valid(11) and valid(12):
            xs = [kp[5][0], kp[6][0], kp[11][0], kp[12][0]]
            ys = [kp[5][1], kp[6][1], kp[11][1], kp[12][1]]
            pad_x = (max(xs) - min(xs)) * 0.15
            regions["torso"] = (
                int(min(xs) - pad_x), int(min(ys)),
                int(max(xs) + pad_x), int(max(ys))
            )

        # Piernas (pantalón/falda): entre caderas y tobillos
        if valid(11) and valid(12):
            y_top = kp[11][1]
            hip_xs = [kp[11][0], kp[12][0]]
            if valid(15) and valid(16):
                y_bottom = max(kp[15][1], kp[16][1])
            elif valid(13) and valid(14):
                y_bottom = max(kp[13][1], kp[14][1])
            else:
                y_bottom = y_top + (person["bbox"][3] - y_top) * 0.7
            pad_x = abs(hip_xs[1] - hip_xs[0]) * 0.5 + 15
            regions["piernas"] = (
                int(min(hip_xs) - pad_x), int(y_top),
                int(max(hip_xs) + pad_x), int(y_bottom)
            )

        return regions

    # ---------- 3. COLOR DOMINANTE DE UNA REGIÓN ----------
    def get_dominant_color(self, region_box, k=3):
        x1, y1, x2, y2 = region_box
        h, w = self.img_rgb.shape[:2]
        x1, y1 = max(0, x1), max(0, y1)
        x2, y2 = min(w, x2), min(h, y2)
        crop = self.img_rgb[y1:y2, x1:x2]

        if crop.size == 0 or crop.shape[0] < 5 or crop.shape[1] < 5:
            return None, None

        pixels = crop.reshape(-1, 3).astype(float)

        # Filtrar píxeles muy oscuros/claros extremos (sombras/brillos) para no sesgar el color
        brightness = pixels.mean(axis=1)
        mask = (brightness > 15) & (brightness < 240)
        if mask.sum() > 20:
            pixels = pixels[mask]

        kmeans = KMeans(n_clusters=min(k, len(pixels)), n_init=5, random_state=42)
        labels = kmeans.fit_predict(pixels)
        counts = np.bincount(labels)
        dominant_rgb = kmeans.cluster_centers_[np.argmax(counts)]

        return dominant_rgb, self._closest_color_name(dominant_rgb)

    def _closest_color_name(self, rgb):
        best_name, best_dist = None, float("inf")
        for name, ref_rgb in self.color_names.items():
            dist = np.linalg.norm(np.array(rgb) - np.array(ref_rgb))
            if dist < best_dist:
                best_dist, best_name = dist, name
        return best_name

    # ---------- 4. PROPORCIONES CORPORALES RELATIVAS (no cm absolutos) ----------
    def get_body_proportions(self, person):
        kp = person["keypoints"]
        conf = person["kp_conf"]

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        def dist(i, j):
            return float(np.linalg.norm(kp[i] - kp[j]))

        # Usamos el ancho de hombros como unidad de referencia relativa
        if not (valid(5) and valid(6)):
            return None
        shoulder_width = dist(5, 6)
        if shoulder_width == 0:
            return None

        props = {"ancho_hombros_px": round(shoulder_width, 1)}

        if valid(11) and valid(12):
            hip_width = dist(11, 12)
            props["ratio_cadera_hombro"] = round(hip_width / shoulder_width, 2)

        if valid(5) and valid(11):
            torso_len = dist(5, 11)
            props["ratio_torso_hombro"] = round(torso_len / shoulder_width, 2)

        if valid(11) and valid(15):
            leg_len = dist(11, 15)
            props["ratio_pierna_hombro"] = round(leg_len / shoulder_width, 2)

        # Estatura aproximada en píxeles (nariz a tobillo promedio) — NO es cm real
        if valid(0) and (valid(15) or valid(16)):
            ankle_y = kp[15][1] if valid(15) else kp[16][1]
            props["altura_aprox_px"] = round(abs(ankle_y - kp[0][1]), 1)

        return props

    # ---------- 5. REPORTE COMPLETO ----------
    def analyze(self):
        self.detect_people()
        self.results = []

        for i, person in enumerate(self.people):
            regions = self.get_clothing_regions(person)
            props = self.get_body_proportions(person)

            clothing = {}
            for region_name, box in regions.items():
                rgb, name = self.get_dominant_color(box)
                if rgb is not None:
                    clothing[region_name] = {"color": name, "rgb": tuple(int(c) for c in rgb), "box": box}

            self.results.append({"idx": i, "clothing": clothing, "proportions": props, "bbox": person["bbox"]})

        return self.results

    def print_report(self):
        print("\n" + "=" * 60)
        print(f"ANÁLISIS DE ROPA Y PROPORCIONES — {self.img_path}")
        print("=" * 60)

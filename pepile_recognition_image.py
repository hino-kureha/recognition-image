from deepface import DeepFace
import cv2
import matplotlib.pyplot as plt
import numpy as np


class FaceComparator:
    def __init__(self, path1, path2, model_name="Facenet512", detector="retinaface"):
        self.path1 = path1
        self.path2 = path2
        self.model_name = model_name
        self.detector = detector
        self.img1 = cv2.imread(path1)
        self.img2 = cv2.imread(path2)

    # ---------- DETECTAR ROSTROS ----------
    def detect_faces(self):
        try:
            faces1 = DeepFace.extract_faces(self.path1, detector_backend=self.detector, enforce_detection=False)
            faces2 = DeepFace.extract_faces(self.path2, detector_backend=self.detector, enforce_detection=False)
        except Exception as e:
            print(f"Error detectando rostros: {e}")
            return None, None
        return faces1, faces2

    # ---------- VERIFICACIÓN: ¿ES LA MISMA PERSONA? ----------
    def verify_identity(self):
        try:
            result = DeepFace.verify(
                img1_path=self.path1,
                img2_path=self.path2,
                model_name=self.model_name,
                detector_backend=self.detector,
                distance_metric="cosine"
            )
        except Exception as e:
            print(f"No se pudo verificar (¿hay rostro en ambas imágenes?): {e}")
            return None

        similitud_pct = round((1 - result['distance'] / result['threshold']) * 100, 2) if result['distance'] < result['threshold'] else round(max(0, 100 - result['distance']*100), 2)

        print(f"¿Misma persona?: {'SÍ' if result['verified'] else 'NO'}")
        print(f"Distancia: {result['distance']:.4f} (umbral: {result['threshold']:.4f})")
        print(f"Modelo usado: {result['model']}")
        return result

    # ---------- ANÁLISIS DE ATRIBUTOS (edad, género, emoción, etnia) ----------
    def analyze_attributes(self, img_path):
        try:
            analysis = DeepFace.analyze(
                img_path=img_path,
                actions=['age', 'gender', 'emotion', 'race'],
                detector_backend=self.detector,
                enforce_detection=False
            )
            return analysis[0] if isinstance(analysis, list) else analysis
        except Exception as e:
            print(f"No se pudo analizar atributos de {img_path}: {e}")
            return None

    # ---------- COMPARAR ATRIBUTOS ENTRE LAS DOS IMÁGENES ----------
    def compare_attributes(self):
        a1 = self.analyze_attributes(self.path1)
        a2 = self.analyze_attributes(self.path2)

        if a1 is None or a2 is None:
            return None

        print("\n--- Atributos Imagen 1 ---")
        print(f"Edad estimada: {a1['age']}")
        print(f"Género: {a1['dominant_gender']} ({a1['gender'][a1['dominant_gender']]:.1f}%)")
        print(f"Emoción: {a1['dominant_emotion']}")

        print("\n--- Atributos Imagen 2 ---")
        print(f"Edad estimada: {a2['age']}")
        print(f"Género: {a2['dominant_gender']} ({a2['gender'][a2['dominant_gender']]:.1f}%)")
        print(f"Emoción: {a2['dominant_emotion']}")

        print("\n--- Diferencias ---")
        print(f"Diferencia de edad estimada: {abs(a1['age'] - a2['age'])} años")
        print(f"¿Mismo género detectado?: {'Sí' if a1['dominant_gender'] == a2['dominant_gender'] else 'No'}")
        print(f"¿Misma emoción dominante?: {'Sí' if a1['dominant_emotion'] == a2['dominant_emotion'] else 'No'}")

        return {"img1": a1, "img2": a2}

    # ---------- VISUALIZAR ROSTROS DETECTADOS ----------
    def plot_faces(self):
        faces1, faces2 = self.detect_faces()
        if not faces1 or not faces2:
            print("No se detectaron rostros en una o ambas imágenes.")
            return

        fig, axs = plt.subplots(1, 2, figsize=(10, 5))
        axs[0].imshow(faces1[0]['face'])
        axs[0].set_title(f"Rostro 1 (confianza: {faces1[0]['confidence']:.2f})")
        axs[1].imshow(faces2[0]['face'])
        axs[1].set_title(f"Rostro 2 (confianza: {faces2[0]['confidence']:.2f})")
        for ax in axs: ax.axis('off')
        plt.show()

    # ---------- PIPELINE COMPLETO ----------
    def run(self):
        print("=" * 50)
        print("DETECCIÓN DE ROSTROS")
        print("=" * 50)
        self.plot_faces()

        print("\n" + "=" * 50)
        print("VERIFICACIÓN DE IDENTIDAD")
        print("=" * 50)
        self.verify_identity()

        print("\n" + "=" * 50)
        print("ANÁLISIS DE ATRIBUTOS")
        print("=" * 50)
        self.compare_attributes()



class SkinToneAnalyzer:
    NOSE, L_EYE, R_EYE = 0, 1, 2
    L_ELBOW, R_ELBOW, L_WRIST, R_WRIST = 7, 8, 9, 10

    @classmethod
    def analyze(cls, img_rgb, person):
        kp, conf = person["keypoints"], person["kp_conf"]

        def valid(i):
            return conf[i] > 0.25 and not (kp[i][0] == 0 and kp[i][1] == 0)

        patches = []
        # parche de mejilla (bajo el ojo, entre ojo y nariz-boca aprox.)
        if valid(cls.NOSE) and valid(cls.L_EYE):
            cx, cy = kp[cls.L_EYE]
            r = 8
            patches.append(cls._sample(img_rgb, cx, cy + 15, r))
        if valid(cls.NOSE) and valid(cls.R_EYE):
            cx, cy = kp[cls.R_EYE]
            r = 8
            patches.append(cls._sample(img_rgb, cx, cy + 15, r))
        # antebrazo, si es visible (brazos descubiertos)
        for a, b in [(cls.L_ELBOW, cls.L_WRIST), (cls.R_ELBOW, cls.R_WRIST)]:
            if valid(a) and valid(b):
                mx, my = (kp[a] + kp[b]) / 2
                patches.append(cls._sample(img_rgb, mx, my, 10))

        pixels = np.vstack([p for p in patches if p is not None]) if patches else None
        if pixels is None or len(pixels) < 5:
            return {"tono": "no detectado"}

        color_rgb = dominant_color(pixels, k=2)
        tono = _closest_label(color_rgb, SKIN_TONE_TABLE) if color_rgb is not None else "no detectado"
        return {"tono": tono}

    @staticmethod
    def _sample(img_rgb, cx, cy, r):
        h, w = img_rgb.shape[:2]
        cx, cy = int(cx), int(cy)
        x0, x1 = max(0, cx - r), min(w, cx + r)
        y0, y1 = max(0, cy - r), min(h, cy + r)
        if x1 <= x0 or y1 <= y0:
            return None
        return img_rgb[y0:y1, x0:x1].reshape(-1, 3)



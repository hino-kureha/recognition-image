class BodyProportions:
    L_SH, R_SH, L_HIP, R_HIP = 5, 6, 11, 12
    L_EAR, R_EAR, L_EYE, R_EYE = 3, 4, 1, 2

    @staticmethod
    def _width_at_y(mask, y, x_range, tilt_deg=None, n_rows=3):
        """Promedia varias filas alrededor de y para reducir ruido de la máscara."""
        h, w = mask.shape
        widths = []
        for dy in range(-n_rows, n_rows + 1):
            yy = int(np.clip(y + dy, 0, h - 1))
            row = mask[yy, :].copy()
            x0, x1 = x_range
            row[:max(0, x0)] = 0
            row[min(w, x1):] = 0
            xs = np.where(row > 0)[0]
            if len(xs):
                widths.append(xs.max() - xs.min())
        if not widths:
            return None
        raw = float(np.median(widths))
        if tilt_deg and tilt_deg > 3:
            corr = np.cos(np.radians(min(tilt_deg, 45)))
            return round(raw * corr, 1) if corr > 0.3 else raw
        return round(raw, 1)

    @classmethod
    def measure(cls, person, mask_entry, orientation):
        kp, conf = person["keypoints"], person["kp_conf"]
        mask = mask_entry["mask"]
        mx1, my1, mx2, my2 = mask_entry["bbox"]
        tilt = orientation.get("_tilt_deg")

        def valid(i):
            return conf[i] > 0.3 and not (kp[i][0] == 0 and kp[i][1] == 0)

        out = {}
        if valid(cls.L_SH) and valid(cls.R_SH):
            y = int((kp[cls.L_SH][1] + kp[cls.R_SH][1]) / 2)
            out["ancho_hombros_px"] = cls._width_at_y(mask, y, (mx1, mx2), tilt)
            out["_y_shoulder"] = y
        if valid(cls.L_HIP) and valid(cls.R_HIP):
            y = int((kp[cls.L_HIP][1] + kp[cls.R_HIP][1]) / 2)
            out["ancho_caderas_px"] = cls._width_at_y(mask, y, (mx1, mx2), tilt)
            out["_y_hip"] = y
        if "_y_shoulder" in out and "_y_hip" in out:
            y = int(out["_y_shoulder"] + (out["_y_hip"] - out["_y_shoulder"]) * 0.58)
            out["ancho_cintura_px"] = cls._width_at_y(mask, y, (mx1, mx2), tilt)
            out["_y_waist"] = y
        return out

    @staticmethod
    def get_px_to_cm_factor(person, ref_pixel_width=None, ref_cm_width=None):
        if ref_pixel_width and ref_cm_width:
            return ref_cm_width / ref_pixel_width
        kp, conf = person["keypoints"], person["kp_conf"]
        L_EAR, R_EAR, L_EYE, R_EYE = 3, 4, 1, 2

        def valid(i):
            return conf[i] > 0.3 and not (kp[i][0] == 0 and kp[i][1] == 0)

        if valid(L_EAR) and valid(R_EAR):
            face_px = np.linalg.norm(kp[L_EAR] - kp[R_EAR])
        elif valid(L_EYE) and valid(R_EYE):
            face_px = np.linalg.norm(kp[L_EYE] - kp[R_EYE]) * 2.2
        else:
            return None
        AVG_FACE_WIDTH_CM = 14.0
        return AVG_FACE_WIDTH_CM / face_px if face_px > 0 else None

    @staticmethod
    def classify_shape(m, confiabilidad):
        if confiabilidad < 0.4:
            return {"tipo": "No confiable", "razon": "Ángulo/pose no permite medir bien la silueta."}
        s, w, h = m.get("ancho_hombros_px"), m.get("ancho_cintura_px"), m.get("ancho_caderas_px")
        if not (s and w and h):
            return {"tipo": "Indeterminado", "razon": "Faltan medidas clave."}
        sh_diff = abs(s - h) / max(s, h) * 100
        whr, wsr = w / h, w / s
        detalles = [f"Hombro:{s}px Cintura:{w}px Cadera:{h}px",
                    f"cintura/cadera={whr:.2f} cintura/hombro={wsr:.2f}"]
        if whr > 0.90 and wsr > 0.90:
            tipo = "Manzana / Ovalado"
        elif sh_diff < 8 and whr < 0.78:
            tipo = "Reloj de arena"
        elif h > s and (h - s) / s * 100 > 8:
            tipo = "Pera / Triángulo"
        elif s > h and (s - h) / h * 100 > 8:
            tipo = "Triángulo invertido"
        else:
            tipo = "Rectángulo"
        return {"tipo": tipo, "detalles": detalles, "waist_hip_ratio": round(whr, 2)}



import cv2
import numpy as np
import matplotlib.pyplot as plt
from ultralytics import YOLO


class BodyPhysiqueAnalyzer:
    # Ancho promedio de cara humana adulta (entre pómulos), usado SOLO como
    # respaldo cuando no hay objeto de referencia. Es una aproximación poblacional,
    # no una medida exacta de la persona en la foto.
    AVG_FACE_WIDTH_CM = 14.0

    def __init__(self, img_path, pose_model="yolov8n-pose.pt",
                 ref_pixel_width=None, ref_cm_width=None):
        """
        ref_pixel_width / ref_cm_width: si tienes un objeto de referencia en la foto
        (ej. una tarjeta de crédito = 8.56 cm de ancho), pasa cuántos píxeles mide
        ese objeto en la imagen y su tamaño real en cm. Esto da conversión px->cm
        PRECISA. Si no los pasas, se usa una calibración aproximada (menos confiable).
        """
        self.img_path = img_path
        self.img_bgr = cv2.imread(img_path)
        if self.img_bgr is None:
            raise FileNotFoundError(f"No se pudo leer {img_path}")
        self.img_rgb = cv2.cvtColor(self.img_bgr, cv2.COLOR_BGR2RGB)

        print("Cargando modelo de pose...")
        self.pose_model = YOLO(pose_model)

        self.ref_pixel_width = ref_pixel_width
        self.ref_cm_width = ref_cm_width
        self.calibration_mode = "objeto_referencia" if (ref_pixel_width and ref_cm_width) else "aproximada_por_cara"

    # ---------- 1. DETECCIÓN DE PERSONAS + POSE ----------
    def detect_people(self, conf=0.4):
        results = self.pose_model(self.img_bgr, conf=conf, verbose=False)[0]
        self.people = []
        if results.keypoints is None or len(results.boxes) == 0:
            print("No se detectaron personas.")
            return []
        for box, kpts in zip(results.boxes, results.keypoints):
            xyxy = box.xyxy[0].cpu().numpy().astype(int)
            kp = kpts.xy[0].cpu().numpy()
            kp_conf = kpts.conf[0].cpu().numpy() if kpts.conf is not None else np.ones(17)
            self.people.append({"bbox": xyxy, "keypoints": kp, "kp_conf": kp_conf})
        print(f"Personas detectadas: {len(self.people)}")
        return self.people

    # ---------- 2. FACTOR DE CONVERSIÓN PX -> CM ----------
    def get_px_to_cm_factor(self, person):
        """
        Si hay objeto de referencia: usa esa escala (misma para toda la imagen,
        asumiendo que todas las personas están a distancia similar de la cámara).
        Si no: aproxima usando el ancho de cara de ESTA persona vs el promedio
        poblacional (menos preciso, sirve solo como orden de magnitud).
        """
        if self.calibration_mode == "objeto_referencia":
            return self.ref_cm_width / self.ref_pixel_width

        # Fallback: ancho de cara vía keypoints de orejas (3,4) u ojos (1,2)
        kp = person["keypoints"]
        conf = person["kp_conf"]

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        if valid(3) and valid(4):  # orejas
            face_px = np.linalg.norm(kp[3] - kp[4])
        elif valid(1) and valid(2):  # ojos
            face_px = np.linalg.norm(kp[1] - kp[2]) * 2.2  # ojos a ancho de cara ~2.2x
        else:
            return None

        if face_px <= 0:
            return None
        return self.AVG_FACE_WIDTH_CM / face_px

    # ---------- 3. MEDIDAS EN PÍXELES Y CM ----------
    def get_measurements(self, person):
        kp = person["keypoints"]
        conf = person["kp_conf"]

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        def dist(i, j):
            return float(np.linalg.norm(kp[i] - kp[j]))

        px_to_cm = self.get_px_to_cm_factor(person)
        m = {"_px_to_cm_factor": px_to_cm, "_modo_calibracion": self.calibration_mode}

        def add(name, i, j):
            if valid(i) and valid(j):
                px = dist(i, j)
                m[f"{name}_px"] = round(px, 1)
                if px_to_cm:
                    m[f"{name}_cm"] = round(px * px_to_cm, 1)

        # COCO keypoints: 0 nariz,1-2 ojos,3-4 orejas,5-6 hombros,7-8 codos,
        # 9-10 muñecas,11-12 caderas,13-14 rodillas,15-16 tobillos
        add("ancho_hombros", 5, 6)
        add("ancho_caderas", 11, 12)
        add("brazo_superior_izq", 5, 7)
        add("antebrazo_izq", 7, 9)
        add("torso_izq", 5, 11)
        add("muslo_izq", 11, 13)
        add("pantorrilla_izq", 13, 15)

        # Estatura aproximada: nariz a tobillo (no es 100% la altura real, falta cabeza y pie)
        if valid(0) and (valid(15) or valid(16)):
            ankle_y = kp[15][1] if valid(15) else kp[16][1]
            altura_px = abs(ankle_y - kp[0][1]) * 1.08  # factor para compensar cabeza/pie no medidos
            m["estatura_aprox_px"] = round(altura_px, 1)
            if px_to_cm:
                m["estatura_aprox_cm"] = round(altura_px * px_to_cm, 1)

        return m

    # ---------- 4. CLASIFICACIÓN DE SOMATOTIPO (tipo de físico) ----------
    def classify_physique(self, m):
        """
        Estimación de somatotipo basada en ratios corporales (no en apariencia visual
        de grasa/músculo, que una IA de visión no puede medir con certeza desde una foto).
        Usa las 3 categorías clásicas de Sheldon como aproximación orientativa:
        - Ectomorfo: hombros y caderas angostos relativo a la altura, extremidades largas
        - Mesomorfo: hombros notablemente más anchos que caderas, torso proporcionado
        - Endomorfo: caderas anchas relativo a hombros, torso más corto relativo a piernas
        """
        if "ancho_hombros_px" not in m or "ancho_caderas_px" not in m:
            return {"tipo": "Indeterminado", "razon": "Faltan puntos clave (hombros/caderas) para estimar."}

        shoulder = m["ancho_hombros_px"]
        hip = m["ancho_caderas_px"]
        shoulder_hip_ratio = shoulder / hip if hip else None

        torso = m.get("torso_izq_px")
        muslo = m.get("muslo_izq_px")
        pantorrilla = m.get("pantorrilla_izq_px")
        pierna_total = (muslo or 0) + (pantorrilla or 0)
        torso_pierna_ratio = (torso / pierna_total) if (torso and pierna_total) else None

        scores = {"ectomorfo": 0, "mesomorfo": 0, "endomorfo": 0}
        detalles = []

        if shoulder_hip_ratio is not None:
            if shoulder_hip_ratio >= 1.35:
                scores["mesomorfo"] += 2
                detalles.append(f"Hombros notablemente más anchos que caderas (ratio {shoulder_hip_ratio:.2f}) → rasgo mesomorfo")
            elif shoulder_hip_ratio <= 1.05:
                scores["endomorfo"] += 2
                detalles.append(f"Hombros y caderas de ancho similar (ratio {shoulder_hip_ratio:.2f}) → rasgo endomorfo")
            else:
                scores["ectomorfo"] += 1
                detalles.append(f"Ratio hombro/cadera moderado ({shoulder_hip_ratio:.2f}) → rasgo ectomorfo/neutro")

        if torso_pierna_ratio is not None:
            if torso_pierna_ratio < 0.75:
                scores["ectomorfo"] += 1
                detalles.append(f"Piernas largas relativo al torso (ratio {torso_pierna_ratio:.2f}) → rasgo ectomorfo")
            elif torso_pierna_ratio > 0.95:
                scores["endomorfo"] += 1
                detalles.append(f"Torso largo relativo a piernas (ratio {torso_pierna_ratio:.2f}) → rasgo endomorfo")
            else:
                scores["mesomorfo"] += 1
                detalles.append(f"Proporción torso/pierna equilibrada ({torso_pierna_ratio:.2f}) → rasgo mesomorfo")

        tipo_dominante = max(scores, key=scores.get)
        return {"tipo": tipo_dominante, "scores": scores, "detalles": detalles}

    # ---------- 5. ANÁLISIS COMPLETO ----------
    def analyze(self):
        self.detect_people()
        self.results = []

        for i, person in enumerate(self.people):
            m = self.get_measurements(person)
            physique = self.classify_physique(m)
            self.results.append({"idx": i, "measurements": m, "physique": physique, "bbox": person["bbox"]})

        return self.results

    def print_report(self):
        print("\n" + "=" * 65)
        print(f"ANÁLISIS DE PROPORCIONES FÍSICAS — {self.img_path}")
        print(f"Modo de calibración: {self.calibration_mode}")
        if self.calibration_mode == "aproximada_por_cara":
            print("⚠ Sin objeto de referencia: las medidas en cm son APROXIMADAS")
            print("  (usan el ancho promedio de cara humana, ±2-4 cm de error típico,")
            print("  y más si la persona está angulada respecto a la cámara).")
        print("=" * 65)

        for r in self.results:
            m = r["measurements"]
            print(f"\nPersona #{r['idx']+1}")
            print("-" * 45)
            for key, val in m.items():
                if key.startswith("_"):
                    continue
                print(f"  {key}: {val}")

            print(f"\n  Somatotipo estimado: {r['physique']['tipo'].upper()}")
            if "scores" in r["physique"]:
                print(f"  Puntajes: {r['physique']['scores']}")
                for d in r["physique"]["detalles"]:
                    print(f"    - {d}")
            else:
                print(f"  ({r['physique']['razon']})")

    # ---------- 6. VISUALIZACIÓN ----------
    def plot(self):
        img_draw = self.img_rgb.copy()
        colors_box = [(255, 0, 0), (0, 255, 0), (0, 100, 255), (255, 165, 0), (180, 0, 255)]
        skeleton = [(5,6),(5,7),(7,9),(6,8),(8,10),(5,11),(6,12),(11,12),
                    (11,13),(13,15),(12,14),(14,16)]

        for r in self.results:
            c = colors_box[r["idx"] % len(colors_box)]
            x1, y1, x2, y2 = r["bbox"]
            cv2.rectangle(img_draw, (x1, y1), (x2, y2), c, 2)
            label = f"P{r['idx']+1}: {r['physique']['tipo']}"
            if "estatura_aprox_cm" in r["measurements"]:
                label += f" ~{r['measurements']['estatura_aprox_cm']}cm"
            cv2.putText(img_draw, label, (x1, max(y1-10, 15)),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.7, c, 2)

            kp = self.people[r["idx"]]["keypoints"]
            kp_conf = self.people[r["idx"]]["kp_conf"]
            for i, j in skeleton:
                if kp_conf[i] > 0.3 and kp_conf[j] > 0.3:
                    p1, p2 = tuple(kp[i].astype(int)), tuple(kp[j].astype(int))
                    cv2.line(img_draw, p1, p2, c, 2)

        plt.figure(figsize=(11, 13))
        plt.imshow(img_draw)
        plt.axis('off')
        plt.title(f"Proporciones físicas por persona (calibración: {self.calibration_mode})")
        plt.show()

    def run(self):
        self.analyze()
        self.print_report()
        self.plot()



import cv2
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from scipy.optimize import linear_sum_assignment
import insightface
from insightface.app import FaceAnalysis


class FaceComparatorPro:
    def __init__(self, path1, path2, det_size=(640, 640), match_threshold=0.45):
        """
        match_threshold: umbral de similitud coseno (0 a 1) para decidir 'misma persona'.
        Con el modelo buffalo_l, >0.45 suele ser la misma persona, <0.20 personas distintas.
        Entre medio es zona ambigua.
        """
        self.path1, self.path2 = path1, path2
        self.match_threshold = match_threshold

        print("Cargando modelo (la primera vez descarga ~350MB, puede tardar un poco)...")
        self.app = FaceAnalysis(name="buffalo_l", providers=["CPUExecutionProvider"])
        self.app.prepare(ctx_id=0, det_size=det_size)
        print("Modelo listo.\n")

        self.img1_bgr = cv2.imread(path1)
        self.img2_bgr = cv2.imread(path2)
        if self.img1_bgr is None or self.img2_bgr is None:
            raise FileNotFoundError("No se pudo leer una de las dos imágenes, revisa la ruta.")

        self.img1_rgb = cv2.cvtColor(self.img1_bgr, cv2.COLOR_BGR2RGB)
        self.img2_rgb = cv2.cvtColor(self.img2_bgr, cv2.COLOR_BGR2RGB)

    # ---------- 1. DETECCIÓN COMPLETA (rostro + landmarks + embedding + edad/género) ----------
    def detect_all(self):
        self.faces1 = self.app.get(self.img1_bgr)
        self.faces2 = self.app.get(self.img2_bgr)
        print(f"Rostros detectados → Imagen 1: {len(self.faces1)} | Imagen 2: {len(self.faces2)}")
        return self.faces1, self.faces2

    # ---------- 2. MATRIZ DE SIMILITUD (coseno entre embeddings de 512-d) ----------
    @staticmethod
    def cosine_sim(a, b):
        return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b)))

    def build_similarity_matrix(self):
        n, m = len(self.faces1), len(self.faces2)
        sim_matrix = np.zeros((n, m))
        for i in range(n):
            for j in range(m):
                sim_matrix[i, j] = self.cosine_sim(self.faces1[i].embedding, self.faces2[j].embedding)
        return sim_matrix

    # ---------- 3. EMPAREJAMIENTO ÓPTIMO (algoritmo húngaro sobre 1-similitud) ----------
    def match_faces(self):
        if not self.faces1 or not self.faces2:
            self.matches, self.sin_pareja_1, self.sin_pareja_2 = [], list(range(len(self.faces1))), list(range(len(self.faces2)))
            return self.matches

        sim_matrix = self.build_similarity_matrix()
        cost_matrix = 1 - sim_matrix  # húngaro minimiza costo, así que usamos 1-similitud
        row_ind, col_ind = linear_sum_assignment(cost_matrix)

        matches, used1, used2 = [], set(), set()
        for i, j in zip(row_ind, col_ind):
            sim = sim_matrix[i, j]
            matches.append({
                "idx1": i, "idx2": j,
                "similitud": round(sim, 4),
                "similitud_pct": round(sim * 100, 1),
                "misma_persona": bool(sim >= self.match_threshold),
            })
            used1.add(i); used2.add(j)

        self.matches = sorted(matches, key=lambda m: -m["similitud"])
        self.sin_pareja_1 = [i for i in range(len(self.faces1)) if i not in used1]
        self.sin_pareja_2 = [j for j in range(len(self.faces2)) if j not in used2]
        return self.matches

    # ---------- 4. PROPORCIONES FACIALES A PARTIR DE LOS 106 LANDMARKS ----------
    @staticmethod
    def compute_proportions(face):
        lm = face.landmark_2d_106
        if lm is None:
            return None

        def d(i, j):
            return float(np.linalg.norm(lm[i] - lm[j]))

        # Índices del esquema de 106 puntos de InsightFace
        face_width   = d(0, 32)     # contorno izquierdo-derecho de la mandíbula
        face_height  = d(16, 82)    # mentón a entre-cejas aprox
        eye_dist     = d(38, 88)    # centro ojo izq - centro ojo der (aprox)
        nose_width   = d(55, 65)
        mouth_width  = d(84, 90)

        if face_width == 0:
            return None

        return {
            "ratio_alto_ancho_cara": round(face_height / face_width, 3),
            "ratio_ojos_ancho_cara": round(eye_dist / face_width, 3),
            "ratio_nariz_ancho_cara": round(nose_width / face_width, 3),
            "ratio_boca_ancho_cara": round(mouth_width / face_width, 3),
        }

    # ---------- 5. REPORTE DETALLADO ----------
    def full_report(self):
        self.detect_all()
        self.match_faces()

        print("\n" + "=" * 65)
        print("REPORTE DETALLADO DE COMPARACIÓN")
        print("=" * 65)

        for rank, m in enumerate(self.matches, 1):
            f1, f2 = self.faces1[m["idx1"]], self.faces2[m["idx2"]]

            print(f"\n{'─'*65}")
            print(f"PAR {rank}: Rostro #{m['idx1']+1} (Imagen 1) ↔ Rostro #{m['idx2']+1} (Imagen 2)")
            print(f"{'─'*65}")
            veredicto = "MISMA PERSONA" if m["misma_persona"] else "PERSONAS DISTINTAS"
            print(f"  Veredicto:        {veredicto}")
            print(f"  Similitud facial: {m['similitud_pct']}%  (umbral usado: {self.match_threshold*100:.0f}%)")

            print(f"\n  -- Imagen 1 --")
            print(f"  Edad estimada:  {int(f1.age)} años")
            print(f"  Género:         {'Hombre' if f1.sex == 'M' else 'Mujer'}")
            print(f"  Score detección: {f1.det_score:.3f}")

            print(f"\n  -- Imagen 2 --")
            print(f"  Edad estimada:  {int(f2.age)} años")
            print(f"  Género:         {'Hombre' if f2.sex == 'M' else 'Mujer'}")
            print(f"  Score detección: {f2.det_score:.3f}")

            print(f"\n  -- Diferencias --")
            print(f"  Diferencia de edad estimada: {abs(int(f1.age) - int(f2.age))} años")
            print(f"  ¿Mismo género detectado?: {'Sí' if f1.sex == f2.sex else 'No'}")

            prop1 = self.compute_proportions(f1)
            prop2 = self.compute_proportions(f2)
            if prop1 and prop2:
                print(f"\n  -- Proporciones faciales (normalizadas por ancho de cara) --")
                for k in prop1:
                    diff_pct = abs(prop1[k] - prop2[k]) / prop1[k] * 100 if prop1[k] != 0 else 0

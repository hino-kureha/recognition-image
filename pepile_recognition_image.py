class ClothingAnalyzer:
    L_SH, R_SH, L_HIP, R_HIP, L_ANKLE, R_ANKLE = 5, 6, 11, 12, 15, 16
    UPPER_LABELS = ["camiseta", "camisa", "blusa", "vestido", "chaqueta",
                    "sudadera con capucha", "abrigo", "suéter", "top deportivo"]
    LOWER_LABELS = ["pantalón largo", "jean", "short", "falda", "vestido",
                    "legging", "pantalón deportivo"]

    def __init__(self):
        self.clip_model = self.clip_preprocess = self.clip_tokenizer = None
        if HAS_CLIP:
            try:
                self.clip_model, _, self.clip_preprocess = open_clip.create_model_and_transforms(
                    "ViT-B-32", pretrained="openai")
                self.clip_tokenizer = open_clip.get_tokenizer("ViT-B-32")
                self.clip_model.eval()
            except Exception:
                self.clip_model = None

    def _clip_classify(self, crop_rgb, labels):
        if self.clip_model is None or crop_rgb.size == 0:
            return None
        from PIL import Image
        img = self.clip_preprocess(Image.fromarray(crop_rgb)).unsqueeze(0)
        text = self.clip_tokenizer([f"una foto de una prenda tipo {l}" for l in labels])
        with torch.no_grad():
            img_f = self.clip_model.encode_image(img)
            txt_f = self.clip_model.encode_text(text)
            img_f /= img_f.norm(dim=-1, keepdim=True)
            txt_f /= txt_f.norm(dim=-1, keepdim=True)
            sims = (img_f @ txt_f.T).squeeze(0)
        return labels[int(sims.argmax())]

    def analyze(self, img_rgb, person, mask_entry):
        kp, conf = person["keypoints"], person["kp_conf"]
        x1, y1, x2, y2 = person["bbox"]

        def valid(i):
            return conf[i] > 0.25 and not (kp[i][0] == 0 and kp[i][1] == 0)

        result = {"prenda_superior": {}, "prenda_inferior": {}}

        if valid(self.L_SH) and valid(self.R_SH) and valid(self.L_HIP) and valid(self.R_HIP):
            y_top = int((kp[self.L_SH][1] + kp[self.R_SH][1]) / 2)
            y_bot = int((kp[self.L_HIP][1] + kp[self.R_HIP][1]) / 2)
            upper_crop = img_rgb[max(0, y_top):max(1, y_bot), x1:x2]
            result["prenda_superior"] = self._describe(upper_crop, mask_entry, y_top, y_bot,
                                                        x1, x2, self.UPPER_LABELS)

            y_top2 = y_bot
            if valid(self.L_ANKLE) or valid(self.R_ANKLE):
                ankles = [kp[i][1] for i in (self.L_ANKLE, self.R_ANKLE) if valid(i)]
                y_bot2 = int(np.mean(ankles))
            else:
                y_bot2 = y2
            lower_crop = img_rgb[max(0, y_top2):max(1, y_bot2), x1:x2]
            result["prenda_inferior"] = self._describe(lower_crop, mask_entry, y_top2, y_bot2,
                                                        x1, x2, self.LOWER_LABELS)
        return result

    def _describe(self, crop_rgb, mask_entry, y0, y1, x0, x1, labels):
        if crop_rgb.size == 0:
            return {"tipo": "no detectado", "color": "no detectado"}

        pixels = crop_rgb.reshape(-1, 3)
        if mask_entry is not None:
            m = mask_entry["mask"][max(0, y0):max(1, y1), x0:x1]
            if m.shape == crop_rgb.shape[:2] and m.any():
                pixels = crop_rgb[m.astype(bool)]

        color_rgb = dominant_color(pixels, k=3)
        color_label = _closest_label(color_rgb, CLOTH_COLOR_NAMES) if color_rgb is not None else "no detectado"

        tipo = self._clip_classify(crop_rgb, labels)
        if tipo is None:
            # heurística de respaldo sin CLIP: forma de la máscara
            tipo = self._shape_heuristic(mask_entry, y0, y1, x0, x1, labels)

        return {"tipo": tipo, "color": color_label}

    @staticmethod
    def _shape_heuristic(mask_entry, y0, y1, x0, x1, labels):
        """Sin CLIP: usa si la región se separa en dos piernas (pantalón/short)
        o queda unida (falda/vestido) y el largo relativo para short vs largo."""
        if mask_entry is None:
            return "prenda (tipo no determinado, instala CLIP para detalle)"
        mask = mask_entry["mask"]
        h = mask.shape[0]
        y0, y1 = max(0, y0), min(h, y1)
        if y1 <= y0:
            return "prenda (tipo no determinado)"
        mid_row = mask[int((y0 + y1) / 2), x0:x1]
        xs = np.where(mid_row > 0)[0]
        if len(xs) == 0:
            return "prenda (tipo no determinado)"
        gap = np.diff(xs)
        splits_into_legs = np.any(gap > (xs.max() - xs.min()) * 0.15)
        if "falda" in labels or "vestido" in labels:  # se está describiendo la parte inferior
            return "pantalón/short (piernas separadas)" if splits_into_legs else "falda/vestido (una sola pieza)"
        return "prenda superior"



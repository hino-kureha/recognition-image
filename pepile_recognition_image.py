import cv2
import numpy as np
from skimage.metrics import structural_similarity as ssim
import matplotlib.pyplot as plt
import matplotlib.patches as patches
from scipy import ndimage


class ImageComparator:
    def __init__(self, path1, path2, align=True, verbose=True):
        self.verbose = verbose
        self.img1_orig = cv2.imread(path1)
        self.img2_orig = cv2.imread(path2)

        if self.img1_orig is None or self.img2_orig is None:
            raise FileNotFoundError("No se pudo cargar una de las imágenes, revisa la ruta.")

        self.img1 = self.img1_orig.copy()
        self.img2 = self.img2_orig.copy()

        # Igualar tamaño
        if self.img1.shape[:2] != self.img2.shape[:2]:
            self.img2 = cv2.resize(self.img2, (self.img1.shape[1], self.img1.shape[0]))

        # Alineación por features (ORB + homografía) para corregir rotación/traslación/escala
        self.align_score = None
        if align:
            self.img2, self.align_score = self._align_images(self.img1, self.img2)

        self.gray1 = cv2.cvtColor(self.img1, cv2.COLOR_BGR2GRAY)
        self.gray2 = cv2.cvtColor(self.img2, cv2.COLOR_BGR2GRAY)

        self.results = {}

    # ---------- ALINEACIÓN ----------
    def _align_images(self, ref, target, max_features=2000, good_match_pct=0.15):
        orb = cv2.ORB_create(max_features)
        gray_ref = cv2.cvtColor(ref, cv2.COLOR_BGR2GRAY)
        gray_target = cv2.cvtColor(target, cv2.COLOR_BGR2GRAY)

        kp1, des1 = orb.detectAndCompute(gray_ref, None)
        kp2, des2 = orb.detectAndCompute(gray_target, None)

        if des1 is None or des2 is None or len(kp1) < 10 or len(kp2) < 10:
            if self.verbose:
                print("No hay suficientes features para alinear, se usa la imagen sin alinear.")
            return target, None

        matcher = cv2.BFMatcher(cv2.NORM_HAMMING, crossCheck=True)
        matches = matcher.match(des1, des2)
        matches = sorted(matches, key=lambda x: x.distance)

        n_good = max(int(len(matches) * good_match_pct), 10)
        matches = matches[:n_good]

        if len(matches) < 4:
            return target, None

        pts1 = np.float32([kp1[m.queryIdx].pt for m in matches]).reshape(-1, 1, 2)
        pts2 = np.float32([kp2[m.trainIdx].pt for m in matches]).reshape(-1, 1, 2)

        H, mask = cv2.findHomography(pts2, pts1, cv2.RANSAC, 5.0)
        if H is None:
            return target, None

        h, w = ref.shape[:2]
        aligned = cv2.warpPerspective(target, H, (w, h))

        inliers_pct = (mask.sum() / len(mask)) * 100 if mask is not None else None
        if self.verbose:
            print(f"Alineación: {len(matches)} matches usados, {inliers_pct:.1f}% inliers")

        return aligned, inliers_pct

    # ---------- SSIM MULTICANAL ----------
    def compute_ssim(self):
        # SSIM por canal de color (más sensible a cambios de color que solo escala de grises)
        score_gray, diff_gray = ssim(self.gray1, self.gray2, full=True)

        scores_color = []
        diffs_color = []
        for ch in range(3):
            s, d = ssim(self.img1[:, :, ch], self.img2[:, :, ch], full=True)
            scores_color.append(s)
            diffs_color.append(d)

        diff_color = np.mean(diffs_color, axis=0)
        score_color = np.mean(scores_color)

        self.results['ssim_gray'] = score_gray
        self.results['ssim_color'] = score_color
        self.diff_map = (diff_color * 255).astype("uint8")
        return score_gray, score_color

    # ---------- HISTOGRAMA DE COLOR ----------
    def compute_histogram_similarity(self):
        hist_sim = []
        for ch in range(3):
            h1 = cv2.calcHist([self.img1], [ch], None, [256], [0, 256])
            h2 = cv2.calcHist([self.img2], [ch], None, [256], [0, 256])
            cv2.normalize(h1, h1)
            cv2.normalize(h2, h2)
            corr = cv2.compareHist(h1, h2, cv2.HISTCMP_CORREL)
            hist_sim.append(corr)
        self.results['histogram_similarity'] = np.mean(hist_sim)
        return self.results['histogram_similarity']

    # ---------- DETECCIÓN DE REGIONES DIFERENTES ----------
    def detect_diff_regions(self, thresh_val=200, min_area=60, dilate_iter=2):
        thresh = cv2.threshold(self.diff_map, thresh_val, 255, cv2.THRESH_BINARY_INV)[1]

        # Dilatar para fusionar regiones cercanas fragmentadas
        kernel = np.ones((5, 5), np.uint8)
        thresh = cv2.dilate(thresh, kernel, iterations=dilate_iter)

        contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        boxes = []
        total_diff_area = 0
        img_area = self.img1.shape[0] * self.img1.shape[1]

        for c in contours:
            area = cv2.contourArea(c)
            if area > min_area:
                x, y, w, h = cv2.boundingRect(c)
                boxes.append({'x': x, 'y': y, 'w': w, 'h': h, 'area': area,
                               'pct_imagen': round(area / img_area * 100, 3)})
                total_diff_area += area

        boxes = sorted(boxes, key=lambda b: b['area'], reverse=True)
        self.results['n_regiones'] = len(boxes)
        self.results['pct_area_diferente'] = round(total_diff_area / img_area * 100, 2)
        self.diff_boxes = boxes
        return boxes

    # ---------- HEATMAP OVERLAY ----------
    def make_heatmap_overlay(self, alpha=0.5):
        heatmap = cv2.applyColorMap(255 - self.diff_map, cv2.COLORMAP_JET)
        overlay = cv2.addWeighted(self.img2, 1 - alpha, heatmap, alpha, 0)
        return overlay

    # ---------- REPORTE ----------
    def report(self):
        print("=" * 50)
        print("REPORTE DE COMPARACIÓN")
        print("=" * 50)
        if self.align_score is not None:
            print(f"Calidad de alineación: {self.align_score:.1f}% inliers")
        print(f"SSIM (gris):        {self.results['ssim_gray']*100:.2f}%")
        print(f"SSIM (color):        {self.results['ssim_color']*100:.2f}%")
        print(f"Similitud histograma: {self.results['histogram_similarity']*100:.2f}%")
        print(f"Área distinta total:  {self.results['pct_area_diferente']}%")
        print(f"Regiones detectadas:  {self.results['n_regiones']}")
        print("-" * 50)
        for i, b in enumerate(self.diff_boxes[:10], 1):
            print(f"  Región {i}: pos=({b['x']},{b['y']}) tamaño={b['w']}x{b['h']} "
                  f"→ {b['pct_imagen']}% de la imagen")
        print("=" * 50)

    # ---------- VISUALIZACIÓN ----------
    def plot(self, max_boxes=15):
        img_marcada = self.img2.copy()
        for b in self.diff_boxes[:max_boxes]:
            cv2.rectangle(img_marcada, (b['x'], b['y']),
                           (b['x'] + b['w'], b['y'] + b['h']), (0, 0, 255), 2)

        overlay = self.make_heatmap_overlay()

        fig, axs = plt.subplots(2, 3, figsize=(20, 12))
        axs[0, 0].imshow(cv2.cvtColor(self.img1, cv2.COLOR_BGR2RGB)); axs[0, 0].set_title("Imagen 1 (referencia)")
        axs[0, 1].imshow(cv2.cvtColor(self.img2, cv2.COLOR_BGR2RGB)); axs[0, 1].set_title("Imagen 2 (alineada)")
        axs[0, 2].imshow(self.diff_map, cmap='gray'); axs[0, 2].set_title("Mapa de diferencias (SSIM)")
        axs[1, 0].imshow(cv2.cvtColor(overlay, cv2.COLOR_BGR2RGB)); axs[1, 0].set_title("Heatmap de diferencias")
        axs[1, 1].imshow(cv2.cvtColor(img_marcada, cv2.COLOR_BGR2RGB)); axs[1, 1].set_title(f"Regiones marcadas (top {max_boxes})")

        # Panel de texto con resumen
        axs[1, 2].axis('off')
        texto = (
            f"SSIM color: {self.results['ssim_color']*100:.2f}%\n"
            f"SSIM gris: {self.results['ssim_gray']*100:.2f}%\n"
            f"Histograma: {self.results['histogram_similarity']*100:.2f}%\n"
            f"Área distinta: {self.results['pct_area_diferente']}%\n"
            f"N° regiones: {self.results['n_regiones']}"
        )
        axs[1, 2].text(0.1, 0.5, texto, fontsize=14, va='center', family='monospace')

        for ax in axs.flat[:5]:
            ax.axis('off')
        plt.tight_layout()
        plt.show()

    # ---------- PIPELINE COMPLETO ----------
    def run(self):
        self.compute_ssim()
        self.compute_histogram_similarity()
        self.detect_diff_regions()
        self.report()
        self.plot()
        return self.results


# Uso

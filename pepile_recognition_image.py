import cv2
import numpy as np
import matplotlib.pyplot as plt
from ultralytics import YOLO


class BodyShapeAnalyzer:
    def __init__(self, img_path, pose_model="yolov8n-pose.pt", seg_model="yolov8n-seg.pt",
                 ref_pixel_width=None, ref_cm_width=None):
        self.img_path = img_path
        self.img_bgr = cv2.imread(img_path)
        if self.img_bgr is None:
            raise FileNotFoundError(f"No se pudo leer {img_path}")
        self.img_rgb = cv2.cvtColor(self.img_bgr, cv2.COLOR_BGR2RGB)

        print("Cargando modelos de pose y segmentación...")
        self.pose_model = YOLO(pose_model)
        self.seg_model = YOLO(seg_model)  # para obtener la silueta real del cuerpo
        print("Modelos listos.\n")

        self.ref_pixel_width = ref_pixel_width
        self.ref_cm_width = ref_cm_width
        self.calibration_mode = "objeto_referencia" if (ref_pixel_width and ref_cm_width) else "sin_calibrar"

    # ---------- 1. POSE (para ubicar niveles de hombro/cintura/cadera) ----------
    def detect_pose(self, conf=0.4):
        results = self.pose_model(self.img_bgr, conf=conf, verbose=False)[0]
        self.people = []
        if results.keypoints is None or len(results.boxes) == 0:
            print("No se detectaron personas.")
            return []
        for box, kpts in zip(results.boxes, results.keypoints):
            xyxy = box.xyxy[0].cpu().numpy().astype(int)
            kp = kpts.xy[0].cpu().numpy()
            kp_conf = kpts.conf[0].cpu().numpy() if kpts.conf is not None else np.ones(17)
            self.people.append({"bbox": xyxy, "keypoints": kp, "kp_conf": kp_conf})
        print(f"Personas detectadas: {len(self.people)}")
        return self.people

    # ---------- 2. SEGMENTACIÓN (silueta real de cada persona) ----------
    def detect_masks(self, conf=0.4):
        results = self.seg_model(self.img_bgr, conf=conf, classes=[0], verbose=False)[0]  # clase 0 = persona
        self.masks = []
        if results.masks is None:
            print("No se detectaron máscaras de segmentación.")
            return []
        h, w = self.img_bgr.shape[:2]
        for mask_data, box in zip(results.masks.data, results.boxes):
            mask = mask_data.cpu().numpy()
            mask_resized = cv2.resize(mask, (w, h))
            self.masks.append({
                "mask": (mask_resized > 0.5).astype(np.uint8),
                "bbox": box.xyxy[0].cpu().numpy().astype(int)
            })
        return self.masks

    # ---------- 3. EMPAREJAR CADA PERSONA (pose) CON SU MÁSCARA (segmentación) ----------
    def match_pose_to_mask(self, person):
        px1, py1, px2, py2 = person["bbox"]
        center = np.array([(px1 + px2) / 2, (py1 + py2) / 2])
        best_mask, best_dist = None, float("inf")
        for m in self.masks:
            mx1, my1, mx2, my2 = m["bbox"]
            mcenter = np.array([(mx1 + mx2) / 2, (my1 + my2) / 2])
            dist = np.linalg.norm(center - mcenter)
            if dist < best_dist:
                best_dist, best_mask = dist, m
        return best_mask

    # ---------- 4. ANCHO REAL DEL CUERPO EN UNA FILA (y) USANDO LA MÁSCARA ----------
    def get_width_at_y(self, mask, y, x_range=None):
        h, w = mask.shape
        y = int(np.clip(y, 0, h - 1))
        row = mask[y, :]
        if x_range:
            x0, x1 = x_range
            row = row.copy()
            row[:max(0, x0)] = 0
            row[min(w, x1):] = 0
        xs = np.where(row > 0)[0]
        if len(xs) == 0:
            return None, None, None
        return int(xs.max() - xs.min()), int(xs.min()), int(xs.max())

    # ---------- 5. MEDIR HOMBRO, CINTURA, CADERA CON LA SILUETA ----------
    def measure_body_shape(self, person, mask_entry):
        kp = person["keypoints"]
        conf = person["kp_conf"]
        mask = mask_entry["mask"]
        mx1, my1, mx2, my2 = mask_entry["bbox"]

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        result = {}

        # Nivel de hombros: promedio de y de ambos hombros (keypoints 5,6)
        if valid(5) and valid(6):
            y_shoulder = int((kp[5][1] + kp[6][1]) / 2)
            w_shoulder, _, _ = self.get_width_at_y(mask, y_shoulder, (mx1, mx2))
            result["ancho_hombros_px"] = w_shoulder
            result["_y_shoulder"] = y_shoulder

        # Nivel de caderas: promedio de y de ambas caderas (keypoints 11,12)
        if valid(11) and valid(12):
            y_hip = int((kp[11][1] + kp[12][1]) / 2)
            w_hip, _, _ = self.get_width_at_y(mask, y_hip, (mx1, mx2))
            result["ancho_caderas_px"] = w_hip
            result["_y_hip"] = y_hip

        # Nivel de cintura: no es un keypoint COCO, se interpola entre hombro y cadera.
        # Anatómicamente la cintura está ~55-60% del camino entre hombro y cadera (más cerca de la cadera).
        if "_y_shoulder" in result and "_y_hip" in result:
            y_waist = int(result["_y_shoulder"] + (result["_y_hip"] - result["_y_shoulder"]) * 0.58)
            w_waist, _, _ = self.get_width_at_y(mask, y_waist, (mx1, mx2))
            result["ancho_cintura_px"] = w_waist
            result["_y_waist"] = y_waist

        return result

    # ---------- 6. CONVERSIÓN PX -> CM ----------
    def get_px_to_cm_factor(self, person):
        if self.calibration_mode == "objeto_referencia":
            return self.ref_cm_width / self.ref_pixel_width

        kp = person["keypoints"]
        conf = person["kp_conf"]
        AVG_FACE_WIDTH_CM = 14.0

        def valid(idx):
            return conf[idx] > 0.3 and not (kp[idx][0] == 0 and kp[idx][1] == 0)

        if valid(3) and valid(4):
            face_px = np.linalg.norm(kp[3] - kp[4])
        elif valid(1) and valid(2):
            face_px = np.linalg.norm(kp[1] - kp[2]) * 2.2
        else:
            return None
        return AVG_FACE_WIDTH_CM / face_px if face_px > 0 else None

    # ---------- 7. CLASIFICACIÓN DE FORMA CORPORAL ----------
    def classify_body_shape(self, m):
        """
        Clasificación estándar basada en ratios hombro/cintura/cadera:
        - Reloj de arena: hombro ≈ cadera, cintura notablemente más angosta que ambos
        - Pera/triángulo: cadera notablemente más ancha que hombro
        - Triángulo invertido: hombro notablemente más ancho que cadera
        - Rectángulo: hombro ≈ cintura ≈ cadera (poca diferencia)
        - Manzana/ovalado: cintura ≈ o más ancha que hombro y cadera
        """
        shoulder = m.get("ancho_hombros_px")
        waist = m.get("ancho_cintura_px")
        hip = m.get("ancho_caderas_px")

        if not (shoulder and waist and hip):
            return {"tipo": "Indeterminado", "razon": "Faltan medidas de hombro/cintura/cadera."}

        shoulder_hip_diff_pct = abs(shoulder - hip) / max(shoulder, hip) * 100
        waist_hip_ratio = waist / hip
        waist_shoulder_ratio = waist / shoulder

        detalles = [
            f"Hombro: {shoulder}px | Cintura: {waist}px | Cadera: {hip}px",
            f"Diferencia hombro-cadera: {shoulder_hip_diff_pct:.1f}%",
            f"Ratio cintura/cadera: {waist_hip_ratio:.2f}",
            f"Ratio cintura/hombro: {waist_shoulder_ratio:.2f}",
        ]

        # Manzana: cintura es casi tan ancha o más que hombro/cadera
        if waist_hip_ratio > 0.90 and waist_shoulder_ratio > 0.90:
            tipo = "Manzana / Ovalado"
            detalles.append("La cintura es casi tan ancha como hombros y caderas → forma manzana")

        # Reloj de arena: hombro y cadera similares, cintura claramente más angosta
        elif shoulder_hip_diff_pct < 8 and waist_hip_ratio < 0.78:
            tipo = "Reloj de arena"
            detalles.append("Hombros y caderas de ancho similar, cintura marcadamente más angosta → reloj de arena")

        # Pera / triángulo: cadera notablemente más ancha que hombro
        elif hip > shoulder and (hip - shoulder) / shoulder * 100 > 8:
            tipo = "Pera / Triángulo"
            detalles.append("Caderas notablemente más anchas que hombros → forma pera")

        # Triángulo invertido: hombro notablemente más ancho que cadera
        elif shoulder > hip and (shoulder - hip) / hip * 100 > 8:
            tipo = "Triángulo invertido"
            detalles.append("Hombros notablemente más anchos que caderas → triángulo invertido")

        # Rectángulo: todo parecido, cintura no muy marcada
        else:
            tipo = "Rectángulo"
            detalles.append("Hombros, cintura y caderas de ancho similar, sin cintura marcada → rectángulo")

        return {"tipo": tipo, "waist_hip_ratio": round(waist_hip_ratio, 2),
                "waist_shoulder_ratio": round(waist_shoulder_ratio, 2), "detalles": detalles}

    # ---------- 8. ANÁLISIS COMPLETO ----------
    def analyze(self):
        self.detect_pose()
        self.detect_masks()
        self.results = []

        for i, person in enumerate(self.people):
            mask_entry = self.match_pose_to_mask(person)

class AccessoryDetector:
    COCO_ACCESSORIES = {24: "mochila", 26: "bolso/cartera", 27: "corbata", 28: "maleta", 25: "paraguas"}

    def __init__(self, yolo_model="yolov8n.pt"):
        self.yolo = YOLO(yolo_model) if HAS_YOLO else None

    def detect(self, img_bgr, person_bbox, conf=0.3):
        found = []
        if self.yolo is not None:
            results = self.yolo(img_bgr, conf=conf, verbose=False)[0]
            px1, py1, px2, py2 = person_bbox
            for box in results.boxes:
                cls_id = int(box.cls[0])
                if cls_id in self.COCO_ACCESSORIES:
                    bx1, by1, bx2, by2 = box.xyxy[0].cpu().numpy()
                    # ¿el accesorio se solapa con la persona?
                    if bx1 < px2 and bx2 > px1 and by1 < py2 and by2 > py1:
                        found.append(self.COCO_ACCESSORIES[cls_id])
        return found



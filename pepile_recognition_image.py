class OrientationEstimator:
    L_SH, R_SH, L_HIP, R_HIP = 5, 6, 11, 12
    L_EAR, R_EAR, L_EYE, R_EYE, NOSE = 3, 4, 1, 2, 0

    @classmethod
    def estimate(cls, person):
        kp, conf = person["keypoints"], person["kp_conf"]
        z = person.get("z")

        def valid(i, th=0.3):
            return conf[i] > th and not (kp[i][0] == 0 and kp[i][1] == 0)

        info = {"vista": "indeterminada", "confiabilidad": 0.0, "razones": [], "_tilt_deg": None}
        both_sh = valid(cls.L_SH) and valid(cls.R_SH)
        both_hip = valid(cls.L_HIP) and valid(cls.R_HIP)

        if not both_sh:
            info.update(vista="perfil o muy angulada", confiabilidad=0.15,
                        razones=["Solo un hombro visible → probable perfil"])
            return info

        score = 1.0
        shoulder_w = np.linalg.norm(kp[cls.L_SH] - kp[cls.R_SH])

        # Señal extra: si tenemos z de MediaPipe, un delta z grande entre
        # hombros = persona rotada respecto a la cámara (más fiable que 2D solo)
        if z is not None and shoulder_w > 0:
            dz = abs(z[cls.L_SH] - z[cls.R_SH])
            if dz > 0.15:
                info["razones"].append(f"Diferencia de profundidad entre hombros ({dz:.2f}) → vista rotada")
                score *= max(0.3, 1 - dz)

        if valid(cls.NOSE):
            mid_x = (kp[cls.L_SH][0] + kp[cls.R_SH][0]) / 2
            centering = abs(kp[cls.NOSE][0] - mid_x) / shoulder_w if shoulder_w else None
            if centering is not None:
                if centering > 0.35:
                    info["vista"] = "3/4 (girada)"
                    score *= 0.6
                else:
                    info["vista"] = "frontal"

        if info["vista"] == "indeterminada":
            info["vista"] = "frontal (asumida)"

        if both_sh and both_hip:
            mid_sh = (kp[cls.L_SH] + kp[cls.R_SH]) / 2
            mid_hip = (kp[cls.L_HIP] + kp[cls.R_HIP]) / 2
            dx, dy = mid_hip[0] - mid_sh[0], mid_hip[1] - mid_sh[1]
            tilt = abs(np.degrees(np.arctan2(dx, dy)))
            info["_tilt_deg"] = tilt
            if tilt > 15:
                info["razones"].append(f"Torso inclinado {tilt:.1f}°")
                score *= max(0.4, 1 - (tilt - 15) / 60)

        if not both_hip:
            info["razones"].append("Caderas no visibles → sin cintura/cadera fiable")
            score *= 0.3

        key_confs = [conf[i] for i in [cls.L_SH, cls.R_SH, cls.L_HIP, cls.R_HIP] if conf[i] > 0]
        if key_confs:
            score *= np.mean(key_confs)

        info["confiabilidad"] = round(float(np.clip(score, 0, 1)), 2)
        return info



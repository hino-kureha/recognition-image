class PersonProfiler:
    def __init__(self, img_path, ref_pixel_width=None, ref_cm_width=None):
        self.img_path = img_path
        self.img_bgr = cv2.imread(img_path)
        if self.img_bgr is None:
            raise FileNotFoundError(f"No se pudo leer {img_path}")
        self.img_rgb = cv2.cvtColor(self.img_bgr, cv2.COLOR_BGR2RGB)
        self.ref_pixel_width = ref_pixel_width
        self.ref_cm_width = ref_cm_width

        print("Cargando modelos (los que estén instalados)...")
        self.pose_est = MultiModelPoseEstimator()
        self.seg_est = MultiModelSegmenter()
        self.hair = HairAnalyzer()
        self.skin = SkinToneAnalyzer()
        self.clothing = ClothingAnalyzer()
        self.accessories = AccessoryDetector()
        print(f"YOLO: {'OK' if HAS_YOLO else 'no instalado'} | "
              f"MediaPipe: {'OK' if HAS_MEDIAPIPE else 'no instalado'} | "
              f"CLIP: {'OK' if HAS_CLIP else 'no instalado'}\n")

    def analyze(self):
        people = self.pose_est.detect(self.img_bgr)
        masks = self.seg_est.detect(self.img_bgr, people)
        print(f"Personas detectadas: {len(people)}")

        self.results = []
        for i, (person, mask_entry) in enumerate(zip(people, masks)):
            orientation = OrientationEstimator.estimate(person)

            entry = {"idx": i, "bbox": person["bbox"], "orientation": orientation}

            if mask_entry is None:
                entry["error"] = "No se pudo obtener silueta (ni YOLO-seg ni MediaPipe)"
                self.results.append(entry)
                continue

            m = BodyProportions.measure(person, mask_entry, orientation)
            px_to_cm = BodyProportions.get_px_to_cm_factor(person, self.ref_pixel_width, self.ref_cm_width)
            if px_to_cm:
                for key in ["ancho_hombros_px", "ancho_cintura_px", "ancho_caderas_px"]:
                    if m.get(key):
                        m[key.replace("_px", "_cm")] = round(m[key] * px_to_cm, 1)
            entry["measurements"] = m
            entry["shape"] = BodyProportions.classify_shape(m, orientation["confiabilidad"])
            entry["mask"] = mask_entry["mask"]

            entry["cabello"] = self.hair.analyze(self.img_rgb, person, mask_entry)
            entry["piel"] = self.skin.analyze(self.img_rgb, person)
            entry["ropa"] = self.clothing.analyze(self.img_rgb, person, mask_entry)
            entry["accesorios"] = self.accessories.detect(self.img_bgr, person["bbox"])

            self.results.append(entry)
        return self.results

    # ---------------------------------------------------------------- report
    def print_report(self):
        print("\n" + "=" * 72)
        print(f"PERFIL DE PERSONA(S) — {self.img_path}")
        print("=" * 72)
        for r in self.results:
            print(f"\nPersona #{r['idx']+1}")
            print("-" * 50)
            if "error" in r:
                print(f"  {r['error']}")
                continue

            o = r["orientation"]
            print(f"  Vista: {o['vista']} | Confiabilidad: {o['confiabilidad']*100:.0f}%")
            for razon in o["razones"]:
                print(f"    - {razon}")

            if o["confiabilidad"] >= 0.4:
                m = r["measurements"]
                for key in ["ancho_hombros_px", "ancho_hombros_cm", "ancho_cintura_px",
                            "ancho_cintura_cm", "ancho_caderas_px", "ancho_caderas_cm"]:
                    if key in m:
                        print(f"  {key}: {m[key]}")
                print(f"  Forma corporal: {r['shape']['tipo'].upper()}")
            else:
                print("  ⚠ Proporciones no confiables con este ángulo/pose.")

            print(f"  Cabello: color={r['cabello'].get('color')} | longitud={r['cabello'].get('longitud')}")
            print(f"  Tono de piel (aprox., por color de píxel): {r['piel'].get('tono')}")
            ps, pi = r["ropa"]["prenda_superior"], r["ropa"]["prenda_inferior"]
            print(f"  Prenda superior: {ps.get('tipo')} (color {ps.get('color')})")
            print(f"  Prenda inferior: {pi.get('tipo')} (color {pi.get('color')})")
            print(f"  Accesorios detectados: {', '.join(r['accesorios']) if r['accesorios'] else 'ninguno'}")

    def plot(self):
        img_draw = self.img_rgb.copy()
        colors = [(255, 0, 0), (0, 200, 0), (0, 120, 255), (255, 150, 0), (200, 0, 255)]
        for r in self.results:
            c = colors[r["idx"] % len(colors)]
            x1, y1, x2, y2 = r["bbox"]
            cv2.rectangle(img_draw, (x1, y1), (x2, y2), c, 2)
            tipo = r["shape"]["tipo"] if "error" not in r else "sin silueta"
            label = f"P{r['idx']+1}: {tipo}"
            cv2.putText(img_draw, label, (x1, max(y1 - 10, 15)),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.55, c, 2)
            if "error" not in r:
                sub = f"{r['cabello'].get('color')} | {r['piel'].get('tono')}"
                cv2.putText(img_draw, sub, (x1, min(y2 + 20, img_draw.shape[0] - 5)),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.5, c, 1)

        plt.figure(figsize=(12, 14))
        plt.imshow(img_draw)
        plt.axis('off')
        plt.title("Perfil de persona: proporciones + atributos visuales")
        plt.tight_layout()
        plt.show()

    def run(self):
        self.analyze()
        self.print_report()
        self.plot()


